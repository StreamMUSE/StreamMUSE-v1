#!/usr/bin/env python
"""Generate the Q1 prompt-batch-selection pilot with paired continuations.

Each prompt candidate is generated exactly once and then reused for every
continuation seed.  This keeps prompt quality and continuation randomness
separate, which the original two-stage runner does not do.
"""

