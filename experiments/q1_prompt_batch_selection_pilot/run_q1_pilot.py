def resolve_device(device_arg: str) -> str:
    if device_arg != "auto":
        return device_arg
    return "cuda" if torch.cuda.is_available() else "cpu"


def parse_npz_ids(npz_ids: str) -> list[str]:
    if not npz_ids.strip():
        return []
    names = []
    for item in npz_ids.replace("\n", ",").split(","):
        item = item.strip()
        if not item:
            continue
        names.append(item if item.endswith(".npz") else f"{item}.npz")
    return names


def parse_seeds(raw: str, label: str) -> list[int]:
    seeds = [int(item.strip()) for item in raw.split(",") if item.strip()]
    if not seeds:
        raise ValueError(f"{label} must contain at least one integer")
    if len(set(seeds)) != len(seeds):
        raise ValueError(f"{label} contains duplicate seeds: {raw}")
    return seeds


def set_seed(seed: int) -> None:
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def write_json(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")


def write_csv(path: Path, fieldnames: list[str], rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


@torch.no_grad()
def score_generated_prompt(
    model,
    generated: torch.Tensor,
    prompt_token_count: int,
    device: str,
    tokenizer,
    max_acc_beats: int,
) -> dict:
    """Score accompaniment content tokens from only the injected prompt beats."""
    sequence = generated.to(device)
    if sequence.ndim == 1:
        sequence = sequence.unsqueeze(0)
    if sequence.shape[1] <= prompt_token_count:
        return {
            "available": False,
            "reason": "no_generated_tokens",
            "generated_token_count": 0,
        }

    all_tokens = sequence[0].detach().cpu().tolist()
    generated_tokens = all_tokens[prompt_token_count:]
    v = tokenizer.vocab
    structural = {
        int(v.beat_marker),
        int(v.bar_token_id),
        int(v.eos_token_id),
        int(v.bos_token_id),
    }
    target_token_indices: list[int] = []
    acc_beat_count = 0
    in_scored_acc = False
    for token_index in range(prompt_token_count, len(all_tokens)):
        token = int(all_tokens[token_index])
        if token == int(v.track_marker_acc):
            acc_beat_count += 1
            in_scored_acc = acc_beat_count <= max_acc_beats
            if not in_scored_acc:
                break
            continue
        if token == int(v.track_marker_mel) or token in structural:
            in_scored_acc = False
            continue
        if in_scored_acc:
            target_token_indices.append(token_index)

    if not target_token_indices:
        return {
            "available": False,
            "reason": "no_scored_accompaniment_content_tokens",
            "all_generated_token_count": len(generated_tokens),
            "all_generated_token_ids": generated_tokens,
            "scored_acc_beats": min(acc_beat_count, max_acc_beats),
            "scored_token_count": 0,
        }

    inputs = sequence[:, :-1]
    logits = model(input_ids=inputs).logits.float()
    logit_positions = torch.tensor(
        [token_index - 1 for token_index in target_token_indices],
        device=logits.device,
        dtype=torch.long,
    )
    targets = sequence[:, target_token_indices]
    selected_logits = logits.index_select(1, logit_positions)
    selected_logprobs = torch.log_softmax(selected_logits, dim=-1).gather(
        dim=-1,
        index=targets.unsqueeze(-1),
    ).squeeze(-1)
    selected = selected_logprobs.flatten()
    selected_tokens = targets.flatten()

    mean_nll = -selected.mean().item()
    return {
        "available": True,
        "definition": (
            "exp(mean NLL of accompaniment content tokens in the first "
            f"{max_acc_beats} generated beats under raw Prompt Model logits)"
        ),
        "all_generated_token_count": len(generated_tokens),
        "all_generated_token_ids": generated_tokens,
        "scored_acc_beats": min(acc_beat_count, max_acc_beats),
        "scored_token_count": int(selected.numel()),
        "mean_nll": mean_nll,
        "ppl": math.exp(min(mean_nll, 80.0)),
        "scored_token_ids": [int(value) for value in selected_tokens.detach().cpu().tolist()],
        "scored_token_logprobs": [float(value) for value in selected.detach().cpu().tolist()],
    }


def convert_prompt_acc_to_offline(prompt_tokenizer, offline_tokenizer, prompt_acc_beat) -> torch.Tensor:
    """Convert prompt_model acc beat format into offline_model acc beat format."""
    prompt_v = prompt_tokenizer.vocab
    offline_v = offline_tokenizer.vocab
    pr = prompt_tokenizer.decode_beats_to_pianoroll(
        [prompt_acc_beat],
        track_marker_id=prompt_v.track_marker_acc,
    )

    beat_width = getattr(offline_v, "default_patch_w", 4)
    if pr.shape[2] < beat_width:
        pr = np.pad(pr, ((0, 0), (0, 0), (0, beat_width - pr.shape[2])), mode="constant")
    elif pr.shape[2] > beat_width:
        pr = pr[:, :, :beat_width]

    tokens = offline_tokenizer._codec.image_to_patch_tokens(pr, strict_mode=True)
    compressed = offline_tokenizer.compress_tokens(
        tokens,
        track_marker=offline_v.track_marker_acc,
    )
    return torch.tensor(compressed, dtype=torch.long)


def inject_prompt_prefix(schedule, prompt_prefix_beats):
    """Replace the first acc generation actions with prompt-generated acc beats."""
    new_schedule = []
    acc_action_idx = 0
    injected = 0

    for step in schedule:
        if step.action in ("generate", "inject_gt"):
            if acc_action_idx < len(prompt_prefix_beats):
                new_schedule.append(type(step)("inject_gt", prompt_prefix_beats[acc_action_idx]))
                injected += 1
            else:
                new_schedule.append(type(step)("generate", None))
            acc_action_idx += 1
        else:
            new_schedule.append(step)

    return new_schedule, injected


def main() -> None:
    args = parse_args()
    device = resolve_device(args.device)
    checkpoint = Path(args.checkpoint)
    prompt_checkpoint = Path(args.prompt_checkpoint)
    data_dir = Path(args.data_dir)
    requested_files = parse_npz_ids(args.npz_ids)
    prompt_seeds = parse_seeds(args.prompt_seeds, "prompt-seeds")
    continuation_seeds = parse_seeds(args.continuation_seeds, "continuation-seeds")

    for path, label in (
        (checkpoint, "continuation checkpoint"),
        (prompt_checkpoint, "prompt checkpoint"),
        (data_dir, "data directory"),
        (OFFLINE_MODEL_DIR, "offline model code"),
        (PROMPT_MODEL_DIR, "prompt model code"),
    ):
        if not path.exists():
            raise FileNotFoundError(f"{label} not found: {path}")
    if not requested_files:
        raise ValueError("npz-ids must contain at least one item")
    missing = [name for name in requested_files if not (data_dir / name).exists()]
    if missing:
        raise FileNotFoundError(f"missing npz files: {', '.join(missing)}")

    offline = load_offline_components()
    model_config = offline.ModelConfig()
    dataset = offline.PianoDataset(
        str(data_dir),
        config=model_config,
        cache_lengths=False,
        mode=args.mode,
    )
    dataset.data_files = requested_files
    converter = offline.MidiConverter(dataset.tokenizer)

    prompt = load_prompt_components()
    prompt_config = prompt.ModelConfig()
    prompt_tokenizer = prompt.PianoMusicTokenizer(config=prompt_config)
    prompt_dataset = SimpleNamespace(
        root_dir=dataset.root_dir,
        data_files=dataset.data_files,
        tokenizer=prompt_tokenizer,
    )

    print(f"Using device: {device}", flush=True)
    print(f"Continuation checkpoint: {checkpoint}", flush=True)
    continuation_model = offline.load_model(
        model_path=str(checkpoint),
        model_config=model_config,
        device=device,
        use_fp16=args.fp16,
    )
    print(f"Prompt checkpoint: {prompt_checkpoint}", flush=True)
    prompt_model = prompt.load_model(
        model_path=str(prompt_checkpoint),
        model_config=prompt_config,
        device=device,
        use_fp16=args.fp16,
    )

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = Path(args.output_dir) / f"{args.run_prefix}_{timestamp}"
    run_dir.mkdir(parents=True, exist_ok=False)
    generator = torch.Generator(device=device if device.startswith("cuda") else "cpu")
    prompt_rows: list[dict] = []
    continuation_rows: list[dict] = []

    config_payload = {
        "created_at": timestamp,
        "npz_ids": requested_files,
        "prompt_seeds": prompt_seeds,
        "continuation_seeds": continuation_seeds,
        "prompt_prefix_beats": args.prompt_prefix_beats,
        "prompt_num_bars": args.prompt_num_bars,
        "prompt_checkpoint": str(prompt_checkpoint),
        "continuation_checkpoint": str(checkpoint),
        "prompt_sampling": {
            "temperature": args.prompt_temperature,
            "top_k": args.prompt_top_k,
            "top_p": args.prompt_top_p,
            "repetition_penalty": args.prompt_repetition_penalty,
        },
        "continuation_sampling": {
            "temperature": args.continuation_temperature,
            "top_k": args.continuation_top_k,
            "top_p": args.continuation_top_p,
            "repetition_penalty": args.continuation_repetition_penalty,
        },
    }
    write_json(run_dir / "run_config.json", config_payload)

    total_outputs = len(requested_files) * len(prompt_seeds) * len(continuation_seeds)
    completed_outputs = 0
    for piece_index, npz_name in enumerate(requested_files, start=1):
        idx = piece_index - 1
        piece_id = Path(npz_name).stem
        piece_dir = run_dir / f"piece_{piece_index:02d}_{piece_id}"
        piece_dir.mkdir()
        base_prep = offline.prepare_generation(dataset, idx, gt_prefix_beats=0)
        gt_name = Path(base_prep["gt_path"]).stem
        tempo = base_prep["metadata"]["bpm"] or 120
        gt_midi = piece_dir / "00_GT.mid"
        converter.gt_to_midi(base_prep["gt_path"], str(gt_midi))

        prompt_prep = prompt.prepare_condition(
            prompt_dataset,
            idx,
            num_bars=args.prompt_num_bars,
        )
        if prompt_prep is None:
            raise RuntimeError(f"not enough bars for prompt stage: {npz_name}")

        for prompt_index, prompt_seed in enumerate(prompt_seeds, start=1):
            set_seed(prompt_seed)
            prompt_max_length = len(prompt_prep["prompt_tokens"]) + args.prompt_max_new_tokens
            prompt_generated = prompt_model.generate_music(
                initial_tokens=prompt_prep["prompt_tokens"],
                device=device,
                max_length=prompt_max_length,
                temperature=args.prompt_temperature,
                top_k=args.prompt_top_k,
                top_p=args.prompt_top_p,
                repetition_penalty=args.prompt_repetition_penalty,
            )
            prompt_scores = score_generated_prompt(
                prompt_model,
                prompt_generated,
                len(prompt_prep["prompt_tokens"]),
                device,
                prompt_tokenizer,
                args.prompt_prefix_beats,
            )
            _, prompt_acc_beats = prompt_tokenizer.parse_generated_sequence(
                prompt_generated.squeeze(0)
            )
            prompt_acc_beats = prompt_acc_beats[: args.prompt_prefix_beats]
            if len(prompt_acc_beats) != args.prompt_prefix_beats:
                raise RuntimeError(
                    f"{piece_id} prompt seed {prompt_seed} generated "
                    f"{len(prompt_acc_beats)} beats, expected {args.prompt_prefix_beats}"
                )
            offline_prefix_beats = [
                convert_prompt_acc_to_offline(prompt_tokenizer, dataset.tokenizer, beat)
                for beat in prompt_acc_beats
            ]

            prompt_label = f"p{prompt_index:02d}_seed{prompt_seed}"
            prompt_midi = piece_dir / f"01_prompt_{prompt_label}.mid"
            converter.beats_to_midi(
                mel_beats=base_prep["mel_beats"][: len(offline_prefix_beats)],
                acc_beats=offline_prefix_beats,
                tempo=tempo,
                save_path=str(prompt_midi),
            )
            prompt_score_path = piece_dir / f"01_prompt_{prompt_label}_token_scores.json"
            write_json(prompt_score_path, prompt_scores)
            prompt_rows.append(
                {
                    "piece_id": piece_id,
                    "npz_file": npz_name,
                    "prompt_index": prompt_index,
                    "prompt_seed": prompt_seed,
                    "prompt_midi": str(prompt_midi.relative_to(run_dir)),
                    "prompt_token_scores": str(prompt_score_path.relative_to(run_dir)),
                    "prompt_generated_beats": len(prompt_acc_beats),
                    "prompt_generated_tokens": prompt_scores.get("all_generated_token_count", ""),
                    "prompt_scored_tokens": prompt_scores.get("scored_token_count", ""),
                    "prompt_mean_nll": prompt_scores.get("mean_nll", ""),
                    "prompt_ppl": prompt_scores.get("ppl", ""),
                }
            )

            for continuation_index, continuation_seed in enumerate(continuation_seeds, start=1):
                set_seed(continuation_seed)
                generator.manual_seed(continuation_seed)
                prep = offline.prepare_generation(dataset, idx, gt_prefix_beats=0)
                prep["schedule"], injected = inject_prompt_prefix(
                    prep["schedule"],
                    offline_prefix_beats,
                )
                if injected != args.prompt_prefix_beats:
                    raise RuntimeError(
                        f"{piece_id} injected {injected} prompt beats, "
                        f"expected {args.prompt_prefix_beats}"
                    )
                if args.max_schedule_steps > 0:
                    prep["schedule"] = prep["schedule"][: args.max_schedule_steps]

                acc_beats, _ = continuation_model.generate_accompaniment(
                    initial_tokens=prep["initial_tokens"],
                    schedule=prep["schedule"],
                    vocab=prep["vocab"],
                    device=device,
                    temperature=args.continuation_temperature,
                    top_k=args.continuation_top_k,
                    top_p=args.continuation_top_p,
                    repetition_penalty=args.continuation_repetition_penalty,
                    generator=generator,
                )
                output_midi = piece_dir / (
                    f"02_{prompt_label}__c{continuation_index:02d}_seed{continuation_seed}.mid"
                )
                converter.beats_to_midi(
                    mel_beats=prep["mel_beats"],
                    acc_beats=acc_beats,
                    tempo=tempo,
                    save_path=str(output_midi),
                )
                completed_outputs += 1
                print(
                    f"[{completed_outputs}/{total_outputs}] {piece_id} "
                    f"prompt={prompt_seed} continuation={continuation_seed}",
                    flush=True,
                )
                continuation_rows.append(
                    {
                        "piece_id": piece_id,
                        "npz_file": npz_name,
                        "prompt_index": prompt_index,
                        "prompt_seed": prompt_seed,
                        "continuation_index": continuation_index,
                        "continuation_seed": continuation_seed,
                        "prompt_ppl": prompt_scores.get("ppl", ""),
                        "prompt_midi": str(prompt_midi.relative_to(run_dir)),
                        "output_midi": str(output_midi.relative_to(run_dir)),
                    }
                )

    prompt_fields = list(prompt_rows[0])
    continuation_fields = list(continuation_rows[0])
    write_csv(run_dir / "prompt_manifest.csv", prompt_fields, prompt_rows)
    write_csv(run_dir / "continuation_manifest.csv", continuation_fields, continuation_rows)

    blind_dir = run_dir / "blind_listening"
    blind_dir.mkdir()
    shuffled = continuation_rows.copy()
    random.Random(args.blind_seed).shuffle(shuffled)
    blind_rows: list[dict] = []
    mapping_rows: list[dict] = []
    for blind_index, row in enumerate(shuffled, start=1):
        blind_id = f"sample_{blind_index:03d}"
        source = run_dir / row["output_midi"]
        target = blind_dir / f"{blind_id}.mid"
        shutil.copy2(source, target)
        blind_rows.append(
            {
                "blind_id": blind_id,
                "overall_score_1_to_5": "",
                "melody_fit_1_to_5": "",
                "accompaniment_quality_1_to_5": "",
                "failure_reason": "",
                "comments": "",
            }
        )
        mapping_rows.append({"blind_id": blind_id, **row})
    write_csv(run_dir / "blind_ratings.csv", list(blind_rows[0]), blind_rows)
    write_csv(run_dir / "blind_mapping_private.csv", list(mapping_rows[0]), mapping_rows)
    print(f"Pilot complete: {run_dir}", flush=True)


if __name__ == "__main__":
    main()
