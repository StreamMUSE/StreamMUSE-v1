@contextmanager
def import_codebase(module_dir: Path):
    """Temporarily import one local model codebase with non-package module names."""
    for name in LOCAL_MODULE_NAMES:
        sys.modules.pop(name, None)

    sys.path.insert(0, str(module_dir))
    try:
        yield importlib.import_module
    finally:
        try:
            sys.path.remove(str(module_dir))
        except ValueError:
            pass


def load_prompt_components():
    with import_codebase(PROMPT_MODEL_DIR) as importer:
        config_mod = importer("config")
        inference_mod = importer("inference")
        tokenizer_mod = importer("my_tokenizer")
    return SimpleNamespace(
        ModelConfig=config_mod.ModelConfig,
        load_model=inference_mod.load_model,
        prepare_condition=inference_mod.prepare_condition,
        PianoMusicTokenizer=tokenizer_mod.PianoMusicTokenizer,
    )


def load_offline_components():
    with import_codebase(OFFLINE_MODEL_DIR) as importer:
        config_mod = importer("config")
        inference_mod = importer("inference")
        dataset_mod = importer("PianoDataset")
        converter_mod = importer("Token2Midi")
    return SimpleNamespace(
        ModelConfig=config_mod.ModelConfig,
        load_model=inference_mod.load_model,
        prepare_generation=inference_mod.prepare_generation,
        PianoDataset=dataset_mod.PianoDataset,
        MidiConverter=converter_mod.MidiConverter,
    )


